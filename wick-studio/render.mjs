#!/usr/bin/env node
// Weekly Wick renderer.
//   node render.mjs <YYYY-MM-DD>                 -> queue/<date>/render.mp4 (1080x1920), thumb.png, captions.srt
//   node render.mjs <YYYY-MM-DD> --wide          -> same video at 1920x1080
//   node render.mjs <YYYY-MM-DD> --card          -> queue/<date>/card.png from card.json (1080x1350)
//   node render.mjs <YYYY-MM-DD> --card --wide   -> card.png at 1600x900
//   --style A|B overrides config.cards.style for a card
//   node render.mjs --pending [days]             -> render every queue/<date> from the last N days (default 10)
//                                                   whose card.json/script.md changed since its last output
// Data folder: $WICK_DIR (the synced Google Drive "wick" folder), default ./samples/wick.
// On failure the reason is written to queue/<date>/error.md and the exit code is 1.
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { blinkAt } from './characters/rig.mjs';
import { frameEnvelope, readWav, synthesize, writeWav } from './lib/audio.mjs';
import { findPacket, flameSizeFor, loadPacket, packetTypeFor, qualifiedCount, signalFor, weekDirection } from './lib/packet.mjs';
import { rasterInOrder } from './lib/pool.mjs';
import { svgToPng } from './lib/raster.mjs';
import { chunkAt, chunkWords, fastFrame, layout, sceneKind } from './lib/fast.mjs';
import { resolveCard } from './lib/card-data.mjs';
import { renderCardSvg } from './lib/cards.mjs';
import { mixSoundtrack, SR, to48k } from './lib/sfx.mjs';
import { parseScript } from './lib/script.mjs';
import { chartPath, validate } from './lib/validate.mjs';

const ROOT = dirname(fileURLToPath(import.meta.url));
const CFG = JSON.parse(readFileSync(join(ROOT, 'config.json'), 'utf8'));
const FPS = CFG.fps;
const GAP = 0.06; // breath between lines — keep it tight
const LEAD_IN = 0.2; // first word lands right after the opening punch
const END_HOLD = 1.6; // CTA card stays up after the last word

class RenderError extends Error {
  constructor(errors, warnings = []) { super(errors.join('\n')); this.errors = errors; this.warnings = warnings; }
}

function args() {
  const argv = process.argv.slice(2);
  const wickDir = resolve(process.env.WICK_DIR || join(ROOT, 'samples', 'wick'));
  if (argv[0] === '--pending') return { pending: true, wickDir, days: Number(argv[1] ?? 10) };
  const [date, ...flags] = argv;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) {
    console.error('usage: ./render.sh <YYYY-MM-DD> [--wide] [--card [--style A|B]]\n       ./render.sh --pending [days]');
    process.exit(2);
  }
  const styleAt = flags.indexOf('--style');
  return {
    date, wickDir, queueDir: join(wickDir, 'queue', date),
    card: flags.includes('--card'), wide: flags.includes('--wide'),
    style: styleAt >= 0 ? flags[styleAt + 1] : CFG.cards.style,
  };
}

function writeError(queueDir, date, err) {
  mkdirSync(queueDir, { recursive: true });
  const lines = [`# Render failed — ${date}`, '', `Generated by wick-studio/render.mjs. Fix the items below and run \`./render.sh ${date}\` again.`, '', '## Errors', ''];
  for (const e of err.errors ?? [String(err.stack ?? err)]) lines.push(`- ${e}`);
  if (err.warnings?.length) { lines.push('', '## Warnings', ''); for (const w of err.warnings) lines.push(`- ${w}`); }
  writeFileSync(join(queueDir, 'error.md'), lines.join('\n') + '\n');
}

// Who is on screen during a segment: first ticker shown, its chart if requested.
function viewFor(seg, packet, queueDir) {
  const sym = seg.onScreen.tickers[0];
  const signal = sym ? signalFor(packet, sym) : null;
  return {
    signal,
    chart: sym && seg.onScreen.chart ? chartPath(queueDir, sym) : null,
    other: seg.onScreen.other,
  };
}

// Lays the spoken clips back to back with only a short breath between them (fast cut).
// Script times give the order; the voice sets the pace. [end] holds for the CTA.
function buildTimeline(script, clips, envs) {
  let cursor = LEAD_IN;
  const placed = script.segments.map((seg, i) => {
    const env = envs[i];
    let a = 0, b = env.length - 1;
    while (a < b && env[a] < 0.06) a++;
    while (b > a && env[b] < 0.06) b--;
    const trimStart = a / FPS, trimEnd = (b + 1) / FPS; // voiced part of the clip
    const start = cursor - trimStart;
    cursor = start + trimEnd + GAP;
    return { seg, clip: clips[i], env, start, voiceStart: start + trimStart, voiceEnd: start + trimEnd };
  });
  const total = placed[placed.length - 1].voiceEnd + END_HOLD;
  placed.forEach((p, i) => { p.until = i + 1 < placed.length ? placed[i + 1].voiceStart - 0.04 : total; });
  placed[0].sceneStart = 0;
  placed.forEach((p, i) => { if (i) p.sceneStart = placed[i - 1].until; });
  return { placed, total };
}

function mouthFor(level, ch) {
  if (level < 0.12) return 'closed';
  if (level > 0.25 && /[ouwOUW]/.test(ch ?? '')) return 'round';
  return level < 0.45 ? 'small' : 'wide';
}

function srtTime(s) {
  const ms = Math.round(s * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
}

function encode({ frames, total, audio, out, W, H }) {
  return new Promise((resolveP, reject) => {
    const ff = spawn('ffmpeg', [
      '-y', '-loglevel', 'error',
      '-f', 'rawvideo', '-pix_fmt', 'rgba', '-s', `${W}x${H}`, '-r', String(FPS), '-i', '-',
      '-i', audio,
      '-c:v', 'libx264', '-preset', 'fast', '-crf', '20', '-pix_fmt', 'yuv420p',
      '-c:a', 'aac', '-b:a', '192k', '-t', total.toFixed(3),
      '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:v', '+bitexact', '-flags:a', '+bitexact',
      '-movflags', '+faststart', out,
    ], { stdio: ['pipe', 'inherit', 'inherit'] });
    ff.on('error', reject);
    ff.on('close', (code) => (code === 0 ? resolveP() : reject(new Error(`ffmpeg exited with ${code}`))));
    (async () => {
      for await (const f of frames) {
        if (!ff.stdin.write(f)) await new Promise((r) => ff.stdin.once('drain', r));
      }
      ff.stdin.end();
    })().catch(reject);
  });
}

// Sound-effect cues that line up with the on-screen hits in lib/fast.mjs.
function cuesFor(placed, count) {
  const cues = [];
  placed.forEach((p, i) => {
    const s = p.sceneStart;
    if (i) cues.push({ at: s - 0.06, kind: 'whoosh' });
    switch (p.kind) {
      case 'chart':
        cues.push({ at: s + 0.12, kind: 'pop' }, { at: s + 0.45, kind: 'stamp' });
        if (p.signal?.earnings_caution) cues.push({ at: s + 0.7, kind: 'stamp' });
        break;
      case 'earnings': cues.push({ at: s + 0.1, kind: 'stamp' }, { at: s + 0.55, kind: 'pop' }); break;
      case 'about': cues.push({ at: s + 0.1, kind: 'pop' }, { at: s + 0.35, kind: 'pop' }); break;
      case 'count':
        for (let k = 0; k < Math.min(count, 10); k++) cues.push({ at: s + 0.2 + k * 0.12, kind: 'pop' });
        cues.push({ at: s + 0.5, kind: 'stamp' });
        break;
      case 'end': cues.push({ at: s + 0.05, kind: 'stamp' }, { at: s + 0.25, kind: 'stamp' }); break;
      default: break;
    }
  });
  return cues;
}

async function renderVideo({ date, wickDir, queueDir, wide }) {
  const scriptPath = join(queueDir, 'script.md');
  if (!existsSync(scriptPath)) throw new RenderError([`script.md not found at ${scriptPath}`]);
  const script = parseScript(readFileSync(scriptPath, 'utf8'));
  const packetPath = findPacket(wickDir, date, packetTypeFor({ scriptType: script.type }));
  const packet = packetPath ? loadPacket(packetPath) : null;
  const { errors, warnings } = validate({ script, packet, queueDir });
  if (errors.length) throw new RenderError(errors, warnings);
  for (const w of warnings) console.warn(`warning: ${w}`);

  const { width: W, height: H } = wide ? CFG.sizes.landscape : CFG.sizes.vertical;
  const L = layout(W, H);
  const work = join(queueDir, '.work');
  console.log(`[1/4] voice (${CFG.tts.engine}:${CFG.tts.voice})`);
  const wavs = synthesize(ROOT, CFG.tts, script.segments.map((s) => s.text), work);
  const clips = wavs.map(readWav);
  const envs = clips.map((c) => frameEnvelope(c, FPS));
  const { placed, total } = buildTimeline(script, clips, envs);
  if (total > script.lengthSec + 3) warnings.push(`voice runs ${total.toFixed(1)} s, longer than length_sec ${script.lengthSec} — trim the script`);

  const count = qualifiedCount(packet);
  const { up } = weekDirection(packet);
  const flameSize = flameSizeFor(count);
  placed.forEach((p, i) => {
    Object.assign(p, viewFor(p.seg, packet, queueDir));
    p.kind = sceneKind({ ...p.seg, signal: p.signal, chart: p.chart, about: p.seg.onScreen.about }, i, count);
    p.chunks = chunkWords(p.seg.text, p.voiceStart, p.voiceEnd);
  });

  console.log('[2/4] soundtrack (voice + beat + sfx)');
  const audioPath = join(work, 'mix.wav');
  mkdirSync(work, { recursive: true });
  writeWav(audioPath, mixSoundtrack({
    total,
    voice: placed.map((p) => ({ at: p.start, samples: to48k(p.clip.samples, p.clip.sampleRate) })),
    cues: cuesFor(placed, count),
  }), SR);

  function stateAt(t) {
    let i = placed.findIndex((p) => t >= p.sceneStart && t < p.until);
    if (i < 0) i = placed.length - 1;
    const p = placed[i];
    const local = Math.floor((t - p.start) * FPS);
    const speaking = local >= 0 && local < p.env.length;
    const level = speaking ? p.env[local] : 0;
    const ch = speaking ? p.seg.text[Math.floor((local / p.env.length) * p.seg.text.length)] : '';
    const mood = p.kind === 'end' ? 'excited' : p.seg.mood;
    return {
      type: script.type, t, total, count,
      seg: { kind: p.kind, start: p.sceneStart, dur: p.until - p.sceneStart, signal: p.signal, chart: p.chart, mood, text: p.seg.text },
      chunk: chunkAt(p.chunks, t),
      wick: { t, mood, mouth: mouthFor(level, ch), blink: blinkAt(t), flameSize, up },
    };
  }

  const nFrames = Math.ceil(total * FPS);
  console.log(`[3/4] frames: ${nFrames} @ ${FPS} fps, ${W}x${H} (${total.toFixed(1)} s)`);
  const mp4 = join(queueDir, 'render.mp4');
  let done = 0;
  await encode({
    total, audio: audioPath, out: mp4, W, H,
    frames: rasterInOrder((function* () {
      for (let f = 0; f < nFrames; f++) {
        yield fastFrame(L, stateAt(f / FPS));
        if (++done % (FPS * 5) === 0) console.log(`      ${done}/${nFrames}`);
      }
    })()),
  });

  console.log('[4/4] captions.srt, thumb.png');
  const srt = placed.map((p, i) => `${i + 1}\n${srtTime(p.voiceStart)} --> ${srtTime(Math.min(p.until, p.voiceEnd + 0.3))}\n${p.seg.text}\n`).join('\n');
  writeFileSync(join(queueDir, 'captions.srt'), srt);
  // Thumbnail = the settled ticker shot (or the hook) with no caption on it.
  const hero = placed.find((p) => p.kind === 'chart') ?? placed[0];
  const thumbState = stateAt(hero.sceneStart + 1.4);
  writeFileSync(join(queueDir, 'thumb.png'), svgToPng(fastFrame(L, { ...thumbState, chunk: null, wick: { ...thumbState.wick, mouth: 'closed', blink: 0 } })));

  rmSync(work, { recursive: true, force: true });
  rmSync(join(queueDir, 'error.md'), { force: true });
  for (const w of warnings) console.warn(`warning: ${w}`);
  console.log(`done: ${mp4}`);
}

function renderCard({ date, wickDir, queueDir, wide, style }) {
  const cardPath = join(queueDir, 'card.json');
  if (!existsSync(cardPath)) throw new RenderError([`card.json not found at ${cardPath}`]);
  let raw;
  try { raw = JSON.parse(readFileSync(cardPath, 'utf8')); } catch (e) { throw new RenderError([`card.json is not valid JSON: ${e.message}`]); }
  if (!['A', 'B'].includes(style)) throw new RenderError([`--style must be A or B (got "${style}")`]);
  const packetPath = findPacket(wickDir, date, packetTypeFor({ template: raw.template }));
  const history = raw.template === 'track' ? recentPackets(wickDir, date, 56) : [];
  const { errors, warnings, card } = resolveCard(raw, packetPath ? loadPacket(packetPath) : null, queueDir, history);
  if (errors.length) throw new RenderError(errors, warnings);
  const out = join(queueDir, 'card.png');
  writeFileSync(out, svgToPng(renderCardSvg(card, { style, size: wide ? 'wide' : 'portrait', handle: CFG.handle })));
  rmSync(join(queueDir, 'error.md'), { force: true });
  for (const w of warnings) console.warn(`warning: ${w}`);
  console.log(`done: ${out}`);
}

// Every packet from the `days` days up to the date, oldest first (the tracker's history).
function recentPackets(wickDir, date, days) {
  const dir = join(wickDir, 'packets');
  if (!existsSync(dir)) return [];
  const from = new Date(Date.parse(`${date}T00:00:00Z`) - days * 86400e3).toISOString().slice(0, 10);
  const out = [];
  for (const f of readdirSync(dir).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f) && f.slice(0, 10) <= date && f.slice(0, 10) >= from).sort()) {
    try { out.push(loadPacket(join(dir, f))); } catch (e) { console.warn(`warning: skipped ${f}: ${e.message}`); }
  }
  return out;
}

const mtime = (p) => (existsSync(p) ? statSync(p).mtimeMs : 0);
// Just enough of card.json / script.md to pick the packet; full checks happen at render.
const peekCard = (p) => { try { return JSON.parse(readFileSync(p, 'utf8')).template; } catch { return null; } };
const peekScript = (p) => readFileSync(p, 'utf8').match(/^\s*type\s*:\s*(\S+)/m)?.[1] ?? null;

// Renders every queue/<date>/ from the last `days` days whose card.json or script.md is
// newer than its output (or has no output yet). A date whose error.md is newer than all of
// its inputs is skipped, so a broken script is not re-rendered every run until Grok fixes it.
async function renderPending({ wickDir, days }) {
  const queue = join(wickDir, 'queue');
  if (!existsSync(queue)) { console.log(`no queue folder at ${queue}`); return 0; }
  const since = new Date(Date.now() + 9 * 3600e3 - days * 86400e3).toISOString().slice(0, 10); // KST
  let failures = 0, done = 0;
  for (const date of readdirSync(queue).filter((d) => /^\d{4}-\d{2}-\d{2}$/.test(d) && d >= since).sort()) {
    const queueDir = join(queue, date);
    const charts = join(queueDir, 'charts');
    const chartTime = existsSync(charts) ? Math.max(0, ...readdirSync(charts).map((f) => mtime(join(charts, f)))) : 0;
    const jobs = [
      { kind: 'card', input: join(queueDir, 'card.json'), output: join(queueDir, 'card.png'), extra: 0 },
      { kind: 'video', input: join(queueDir, 'script.md'), output: join(queueDir, 'render.mp4'), extra: chartTime },
    ];
    for (const job of jobs) {
      if (!existsSync(job.input)) continue;
      const packet = findPacket(wickDir, date, packetTypeFor(job.kind === 'card' ? { template: peekCard(job.input) } : { scriptType: peekScript(job.input) }));
      const newestInput = Math.max(mtime(job.input), packet ? mtime(packet) : 0, job.extra);
      if (mtime(job.output) >= newestInput) continue; // up to date
      if (mtime(join(queueDir, 'error.md')) >= newestInput) continue; // already failed on these inputs
      const opts = { date, wickDir, queueDir, wide: false, style: CFG.cards.style };
      console.log(`== ${date} ${job.kind}`);
      try {
        if (job.kind === 'card') renderCard(opts); else await renderVideo(opts);
        done++;
      } catch (err) {
        failures++;
        writeError(queueDir, date, err);
        console.error(`render failed — see ${join(queueDir, 'error.md')}\n${err.message}`);
      }
    }
  }
  console.log(`pending: ${done} rendered, ${failures} failed`);
  return failures;
}

const opts = args();
if (opts.pending) process.exit((await renderPending(opts)) ? 1 : 0);
try {
  if (opts.card) renderCard(opts);
  else await renderVideo(opts);
} catch (err) {
  writeError(opts.queueDir, opts.date, err);
  console.error(`render failed — see ${join(opts.queueDir, 'error.md')}\n${err.message}`);
  process.exit(1);
}
